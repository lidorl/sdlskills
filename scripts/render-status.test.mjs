const FIX = join(dirname(fileURLToPath(import.meta.url)), 'fixtures');
const NOW = new Date('2026-11-20T12:00:00Z');
const stripStamp = (t) => t.split('\n').filter((l) => !l.startsWith('_Generated by')).join('\n');

function copyFixture() {
  const root = mkdtempSync(join(tmpdir(), 'render-status-'));
  cpSync(join(FIX, 'render-status'), root, { recursive: true });
  return root;
}
function put(root, file, text) {
  mkdirSync(dirname(join(root, file)), { recursive: true });
  writeFileSync(join(root, file), text);
}
const worker = (id, owner, extra = '') =>
  `id: ${id}\nowner: ${owner}\nname: n-${id}\nhost: mac\nagent: claude-code\nmodel: opus\ncreated_at: 2026-11-01T00:00:00Z\nretired_at: null\n${extra}`;
const request = (id, forWho, created, effort = 'alpha') =>
  `---\nid: ${id}\nkind: question\nfor: ${forWho}\nstatus: open\nscope: effort\neffort: ${effort}\nworker: w\ncreated_at: ${created}\n---\n\n## Context\nx\n`;

function boardRoot() {
  const root = copyFixture();
  // alpha: live claim (2h5m old), beta: stale claim (3d old)
  const fr = (slug, status, fm) => put(root, `docs/feat-req/${slug}.md`, `---\nstatus: ${status}\npriority: high\nseverity: minor\ndate: 2026-11-01\n${fm}---\n\n# ${slug}\n`);
  fr('alpha', 'IN_PROGRESS', 'claimed_by: zed-aaaaaa\nclaimed_at: 2026-11-20T09:55:00Z\n');
  fr('beta', 'PLANNED', 'claimed_by: amy-bbbbbb\nclaimed_at: 2026-11-17T12:00:00Z\n');
  put(root, 'board/workers/zed-aaaaaa.yml', worker('zed-aaaaaa', 'zed'));
  put(root, 'board/workers/amy-bbbbbb.yml', worker('amy-bbbbbb', 'amy'));
  put(root, 'board/workers/amy-aaaaaa.yml', worker('amy-aaaaaa', 'amy'));
  put(root, 'board/requests/202611200800-aaaaaa.md', request('202611200800-aaaaaa', 'approvers', '2026-11-20T08:00:00Z'));
  put(root, 'board/requests/202611200900-bbbbbb.md', request('202611200900-bbbbbb', 'zed', '2026-11-20T09:00:00Z'));
  put(root, 'board/requests/202611200700-cccccc.md', request('202611200700-cccccc', 'zed', '2026-11-20T07:00:00Z'));
  return root;
}
const events = [
  { kind: 'start', worker: 'zed-aaaaaa', at: new Date('2026-11-20T09:00:00Z') },
  { kind: 'renew', worker: 'zed-aaaaaa', at: new Date('2026-11-20T11:55:00Z') },
  { kind: 'start', worker: 'amy-bbbbbb', at: new Date('2026-11-17T11:00:00Z') },
];

test('no board/: STATUS.md and .status.json identical to the pre-change renderer output', () => {
  const root = copyFixture();
  const { md, json } = renderStatus({ root, now: NOW });
  assert.equal(stripStamp(md), stripStamp(readFileSync(join(FIX, 'render-status-golden.md'), 'utf8')));
  const gold = JSON.parse(readFileSync(join(FIX, 'render-status-golden.json'), 'utf8'));
  assert.deepEqual({ ...json, generated: 0 }, { ...gold, generated: 0 });
});

test('humanAge: minutes, hours with minutes, days', () => {
  assert.equal(humanAge(20e3), '<1m');
  assert.equal(humanAge(5 * 60e3), '5m');
  assert.equal(humanAge((2 * 60 + 5) * 60e3), '2h 5m');
  assert.equal(humanAge(2 * 3600e3), '2h');
  assert.equal(humanAge(3 * 86400e3 + 5 * 3600e3), '3d');
});

test('board/: Workers grouped by owner, Inbox grouped by for, claim columns with stale flag', () => {
  const root = boardRoot();
  const { md, json } = renderStatus({ root, now: NOW, events });
  const at = (s) => { const i = md.indexOf(s); assert.ok(i >= 0, `missing: ${s}`); return i; };

  at('## Workers');
  assert.ok(at('### amy') < at('### zed'), 'owners sorted');
  assert.ok(at('| amy-aaaaaa |') < at('| amy-bbbbbb |'), 'workers sorted by id within owner');
  at('| Worker | Name | Host | Agent / model | State | Effort | Last seen |');
  assert.match(md, /\| zed-aaaaaa \| n-zed-aaaaaa \| mac \| claude-code \/ opus \| working \| alpha \| 5m ago \|/);
  assert.match(md, /\| amy-bbbbbb \| .* \| stale \| beta \| 3d ago \|/);
  assert.match(md, /\| amy-aaaaaa \| .* \| stopped \| - \| - \|/);
  assert.match(md, /State is derived from the last 2000 board commits\./);

  const inbox = md.slice(at('## Inbox'));
  assert.ok(inbox.indexOf('### zed') < inbox.indexOf('### approvers'), 'approvers last');
  assert.ok(inbox.indexOf('202611200700-cccccc') < inbox.indexOf('202611200900-bbbbbb'), 'oldest first');
  assert.match(inbox, /\| Request \| Kind \| Effort \| Age \|/);
  assert.match(inbox, /\| 202611200700-cccccc \| question \| alpha \| 5h \|/);

  assert.match(md, /### In Progress\n\| Feature \| Status \| Pri \| Sev \| Plan \| PRs \| Age \| Claimant \| Claim age \| Stale \|/);
  assert.match(md, /\| zed-aaaaaa \| 2h 5m \|  \|\n/);
  assert.match(md, /\| amy-bbbbbb \| 3d \| yes \|\n/);

  assert.equal(json.workers.length, 3);
  assert.equal(json.workers.find((w) => w.id === 'zed-aaaaaa').state, 'working');
  assert.equal(json.requests.length, 3);
  assert.equal(json.features.length, 6);
});

